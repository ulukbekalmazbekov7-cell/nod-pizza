-- Удаляем устаревшие критерии из автоподгруппы «Общее», если иерархия уже загружена.
delete from public.inspection_criteria ic
using public.inspection_subcategories s
where ic.subcategory_id = s.id
  and s.name = 'Общее'
  and exists (
    select 1
    from public.inspection_subcategories s2
    where s2.category_id = s.category_id and s2.name <> 'Общее'
  );

delete from public.inspection_subcategories s
